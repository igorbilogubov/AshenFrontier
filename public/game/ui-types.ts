type UiId = keyof typeof elementTags;
type UiElement<Id extends UiId> = HTMLElementTagNameMap[typeof elementTags[Id]];

export function element<Id extends UiId>(id: Id): UiElement<Id>;
export function element(id: string): HTMLElement;
export function element(id: string): HTMLElement {
  const node = document.getElementById(id);
  if (!(node instanceof HTMLElement)) throw new Error(`Missing interface element: ${id}`);
  const expected = elementTags[id as UiId];
  if (expected && node.tagName.toLowerCase() !== expected) throw new Error(`Unexpected interface element: ${id}`);
  return node;
}

export const errorMessage = (error: unknown): string => error instanceof Error ? error.message : String(error);
